// Builds reports/RESULTS.md from the stored evaluation detail files. No number is typed by hand: every cell is recomputed here with
// src/scoring.mjs from the stored predictions (re-scored against the CURRENT annotations, so first-look predictions are compared to the
// corrected synthetic label policy as well as to the original one).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { aggregate, scoreReceipt } from "../src/scoring.mjs";

const FUEL = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const R = (f) => path.join(FUEL, "reports", f);
const J = (f) => JSON.parse(fs.readFileSync(R(f), "utf8"));
const ann = Object.fromEntries(JSON.parse(fs.readFileSync(path.join(FUEL, "corpus", "annotations.json"), "utf8")).records.map((r) => [r.receipt_id, r]));
const annOld = Object.fromEntries(JSON.parse(fs.readFileSync(path.join(FUEL, "corpus", "annotations.before-label-policy-correction.json"), "utf8")).records.map((r) => [r.receipt_id, r]));

const load = (details, groups, labels = ann) => {
  const d = J(details);
  const rows = [];
  for (const g of groups) for (const r of d[g] || []) rows.push({ ...scoreReceipt(r.pred, labels[r.id]), family: r.family, difficulty: r.difficulty, group: g });
  return rows;
};
const pct = (x) => (x.d ? `${x.n}/${x.d} (${Math.round(100 * x.rate)}%)` : "0/0");
const fc = (x) => `${x.n}/${x.d}`;
const row = (name, rows) => {
  const a = aggregate(rows);
  return `| ${name} | ${a.receipts} | ${pct(a.pump_name.exact_rate)} | ${pct(a.transaction_date.exact_rate)} | ${pct(a.total_amount.exact_rate)} | ${fc(a.pump_name.false_confident_per_receipt)} / ${fc(a.transaction_date.false_confident_per_receipt)} / ${fc(a.total_amount.false_confident_per_receipt)} | ${pct(a.overall.review_required_rate)} | ${pct(a.overall.false_accept_rate)} | ${pct(a.overall.true_accept)} |`;
};
const HEAD = "| run | receipts | pump_name exact | transaction_date exact | total_amount exact | false-confident (pump / date / amount) | review required | FALSE ACCEPT | true accept |\n|---|---|---|---|---|---|---|---|---|";
const out = [];
const p = (s = "") => out.push(s);

const BASE = "baseline-ALL-final.details.json"; // the existing pipeline, unchanged, over EVERY group (re-run after heldout2 existed)
const FIN = "improved-v9-FINAL-ALL.details.json";

p("# Fuel-receipt extraction - results (generated by scripts/make_report.mjs; do not edit by hand)\n");
p("Fields scored: `pump_name`, `transaction_date`, `total_amount` ONLY. Exact match uses the normalisation policy in `src/scoring.mjs`. Denominators are receipts with a label for the field (a label of null means 'the correct output is nothing').");
p("**FALSE ACCEPT** = the record would be used with no human review while at least one field is wrong (for non-fuel controls: not held for review). **false-confident** = a wrong value on a field not flagged for review.\n");

p("## 1. Corpus (what was actually measured)\n");
const counts = {};
for (const r of Object.values(ann)) { const k = `${r.source_type} / ${r.split}`; counts[k] = (counts[k] || 0) + 1; }
p("| group | receipts | label provenance |\n|---|---|---|");
const prov = { "authentic / dev": "assistant-verified from the page image (NOT independently human-verified)", "authentic / heldout": "assistant-verified from the page image (NOT independently human-verified)", "synthetic / dev": "construction truth", "synthetic / heldout": "construction truth", "synthetic / heldout2": "construction truth", "generic_control / control": "construction truth (non-fuel: correct outcome = hold for review)", "suspected_template_generated / heldout": "assistant-verified; layout resembles public generator templates, NOT counted as authentic" };
for (const [k, n] of Object.entries(counts)) p(`| ${k} | ${n} | ${prov[k] || ""} |`);
p("\n**Authentic receipts cover only three brands - BPCL, HP and IndianOil. There are no authentic Nayara, Jio-bp or Shell receipts, no independent dealers with unfamiliar layouts beyond what those three include, and the 22 authentic receipts come from 7 expense reports (so they share photographers, scanners and printers).** n = 22 is far too small to estimate real-world accuracy.\n");

p("## 2. Headline: existing pipeline vs improved extractor\n");
p("Groups whose results informed a change are marked. `first look` = the one run made before any change was made in response to that group.\n");
p(HEAD);
p(row("**authentic dev** (12) - baseline", load(BASE, ["authentic_dev"])));
p(row("authentic dev - improved FINAL (tuned on these)", load(FIN, ["authentic_dev"])));
p(row("**authentic held-out** (10) - baseline", load(BASE, ["authentic_heldout"])));
p(row("authentic held-out - improved, **FIRST LOOK** (unbiased)", load("improved-v5-HELDOUT-FIRSTLOOK.details.json", ["authentic_heldout"])));
p(row("authentic held-out - improved FINAL (NO LONGER HELD OUT: fixes were made after the first look)", load(FIN, ["authentic_heldout"])));
p(row("**authentic ALL 22** - baseline", load(BASE, ["authentic_dev", "authentic_heldout"])));
p(row("authentic ALL 22 - improved FINAL (every receipt now consumed; optimistic)", load(FIN, ["authentic_dev", "authentic_heldout"])));
p("");
p(HEAD);
p(row("**synthetic dev** (30) - baseline", load(BASE, ["synthetic_dev"])));
p(row("synthetic dev - improved FINAL (tuned on these)", load(FIN, ["synthetic_dev"])));
p(row("**synthetic held-out** (48) - baseline", load(BASE, ["synthetic_heldout"])));
p(row("synthetic held-out - improved FIRST LOOK, labels as first used", load("improved-v5-HELDOUT-FIRSTLOOK.details.json", ["synthetic_heldout"], annOld)));
p(row("synthetic held-out - improved FIRST LOOK, re-scored with the corrected label policy (see section 5)", load("improved-v5-HELDOUT-FIRSTLOOK.details.json", ["synthetic_heldout"])));
p(row("synthetic held-out - improved FINAL (no longer held out)", load(FIN, ["synthetic_heldout"])));
p(row("**synthetic held-out2** (48, written after the first look) - baseline", load("baseline-HELDOUT2.details.json", ["synthetic_heldout2"])));
p(row("synthetic held-out2 - improved **FIRST LOOK** (clean)", load("improved-v7-HELDOUT2-FIRSTLOOK.details.json", ["synthetic_heldout2"])));
p(row("synthetic held-out2 - improved FINAL (no longer held out: two fixes followed its first look)", load(FIN, ["synthetic_heldout2"])));
p("");
p(HEAD);
p(row("**generic non-fuel controls** (24) - baseline", load(BASE, ["generic_controls"])));
p(row("generic non-fuel controls - improved FINAL", load(FIN, ["generic_controls"])));
p(row("**suspected template-generated page** (1) - baseline", load(BASE, ["suspected_template_generated"])));
p(row("suspected template-generated page - improved FINAL", load(FIN, ["suspected_template_generated"])));
p("\nSynthetic and authentic scores are NEVER combined into one figure. A synthetic result is not evidence of accuracy on authentic Indian fuel receipts.\n");

p("## 3. Attribution: how much comes from the OCR retry and how much from the parser?\n");
p("Authentic (all 22, consumed - optimistic) and synthetic (dev + both held-out sets, 126 receipts).\n");
p(HEAD);
const combos = [["old parser + single-pass OCR (= baseline)", BASE], ["old parser + improved OCR (retry)", "attr-baselineparser-retryOCR.details.json"], ["new parser + single-pass OCR", "attr-improvedparser-singleOCR.details.json"], ["new parser + improved OCR (= final)", FIN]];
for (const [name, f] of combos) p(row(`authentic 22: ${name}`, load(f, ["authentic_dev", "authentic_heldout"])));
for (const [name, f] of combos) p(row(`synthetic 126: ${name}`, load(f, ["synthetic_dev", "synthetic_heldout", "synthetic_heldout2"])));

p("\n### 3b. Dates: guessing vs holding\n");
p("The existing parser reads a numeric date day-first without any evidence, so it can score well on receipts where day-first happens to be right, while being unable to tell a proven date from a guess. `resolvable on the receipt alone` = a careful reader can establish the date from the receipt (a component > 12, equal components, a month name, ISO). `ambiguous on the receipt alone` = day and month are both <= 12 with no proof on the receipt.\n");
p("| run | receipts | date exact on RESOLVABLE receipts | ambiguous-alone receipts | ... a date was returned | ... returned AND marked usable (no review) | ... held for review | wrong date marked usable |\n|---|---|---|---|---|---|---|---|");
const dateRow = (name, rows) => {
  const d = aggregate(rows).transaction_date;
  const amb = rows.filter((r) => r.transaction_date.labelled && r.transaction_date.ambiguousAlone);
  return `| ${name} | ${rows.length} | ${d.resolvable_on_receipt_alone.exact}/${d.resolvable_on_receipt_alone.receipts} | ${amb.length} | ${amb.filter((r) => r.transaction_date.returned).length} | ${amb.filter((r) => r.transaction_date.autoUsable).length} | ${amb.filter((r) => !r.transaction_date.autoUsable).length} | ${rows.filter((r) => r.transaction_date.falseConfident).length} |`;
};
for (const [name, f] of [["old parser + single-pass OCR (= baseline)", BASE], ["new parser + improved OCR (= final)", FIN]]) p(dateRow(`authentic 22: ${name}`, load(f, ["authentic_dev", "authentic_heldout"])));
p("\n## 4. Final extractor by receipt family and by difficulty\n");
const byKey = (rows, keyFn) => { const m = {}; for (const r of rows) for (const k of keyFn(r)) (m[k] ||= []).push(r); return m; };
const table = (title, rows, keyFn) => {
  p(`### ${title}\n`);
  p("| key | n | pump exact | date exact | amount exact | review | false accept |\n|---|---|---|---|---|---|---|");
  for (const [k, rs] of Object.entries(byKey(rows, keyFn)).sort()) {
    const a = aggregate(rs);
    p(`| ${k} | ${rs.length} | ${a.pump_name.exact_rate.n}/${a.pump_name.labelled} | ${a.transaction_date.exact_rate.n}/${a.transaction_date.labelled} | ${a.total_amount.exact_rate.n}/${a.total_amount.labelled} | ${a.overall.review_required_rate.n}/${rs.length} | ${a.overall.false_accept_rate.n}/${rs.length} |`);
  }
  p("");
};
const authRows = load(FIN, ["authentic_dev", "authentic_heldout"]);
table("Authentic - by layout family (22 receipts; consumed)", authRows, (r) => [r.family]);
table("Authentic - by difficulty tag (a receipt can carry several tags)", authRows, (r) => r.difficulty || []);
const synRows = load(FIN, ["synthetic_dev", "synthetic_heldout", "synthetic_heldout2"]);
table("Synthetic - by layout family", synRows, (r) => [`${r.group.replace("synthetic_", "")}:${r.family}`]);
table("Synthetic - by image degradation", synRows, (r) => r.difficulty || []);

p("## 5. Label-policy correction disclosed\n");
p("After the first held-out look, 7 of the synthetic held-out `pump_name` 'false-confident' results turned out to be a label-design error: the jio-bp and Shell synthetic labels accepted only `<brand> <dealer>` while the authentic policy (and the brief: prefer the printed dealer name) also accepts the dealer alone. The dealer-only form was added to the labels of those two templates only; the generator, images and printed text did not change. Both scorings are shown in section 2.\n");

const timing = fs.existsSync(R("timing.json")) ? J("timing.json") : null;
if (timing) {
  p("## 6. Processing time and hardware\n");
  p(`Hardware: ${timing.hardware.cpu}, ${timing.hardware.cores} logical cores, ${timing.hardware.ramGB} GB RAM, ${timing.hardware.platform}, Node ${timing.hardware.node}. CPU only; no GPU; OCR is tesseract.js (WASM); no network.\n`);
  p("| OCR mode | images | mean OCR ms/image | median | p95 | worst | images that needed the retry | extractor ms/image |\n|---|---|---|---|---|---|---|---|");
  for (const [m, t] of Object.entries(timing.modes)) p(`| ${m} | ${t.images} | ${Math.round(t.mean_ocr_ms)} | ${Math.round(t.median_ocr_ms)} | ${Math.round(t.p95_ocr_ms)} | ${Math.round(t.worst_ocr_ms)} | ${t.retried_images} | ${t.extract_ms_mean.toFixed(2)} |`);
  p("");
}
fs.writeFileSync(R("RESULTS.md"), out.join("\n"));
console.log("wrote reports/RESULTS.md");
