// Phase-2 results, generated from stored runs (no hand-typed numbers): reports/RESULTS_PHASE2.md
// Authentic and synthetic receipts are reported separately, each with numerator/denominator, review rate and false-confident rate.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { aggregate, scoreReceipt } from "../src/scoring.mjs";
import { loadAnnotations } from "../src/labels.mjs";
import { lockStatus } from "../src/codeHash.mjs";

const FUEL = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const R = (f) => path.join(FUEL, "reports", f);
const J = (f) => JSON.parse(fs.readFileSync(R(f), "utf8"));
const { records, summary: labelSummary } = loadAnnotations(FUEL, { labels: "all" });
const ann = Object.fromEntries(records.map((r) => [r.receipt_id, r]));
const load = (details, groups) => {
  const d = J(details);
  const rows = [];
  for (const g of groups) for (const r of d[g] || []) rows.push({ ...scoreReceipt(r.pred, ann[r.id]), family: r.family, difficulty: r.difficulty, group: g });
  return rows;
};
const pct = (x) => (x.d ? `${x.n}/${x.d} (${Math.round(100 * x.rate)}%)` : "0/0");
const fc = (x) => `${x.n}/${x.d}`;
const HEAD = "| run | receipts | pump_name exact | transaction_date exact | total_amount exact | review required | false-confident per receipt (pump / date / amount) | FALSE ACCEPT | true accept |\n|---|---|---|---|---|---|---|---|---|";
const row = (name, rows) => {
  const a = aggregate(rows);
  return `| ${name} | ${a.receipts} | ${pct(a.pump_name.exact_rate)} | ${pct(a.transaction_date.exact_rate)} | ${pct(a.total_amount.exact_rate)} | ${pct(a.overall.review_required_rate)} | ${fc(a.pump_name.false_confident_per_receipt)} / ${fc(a.transaction_date.false_confident_per_receipt)} / ${fc(a.total_amount.false_confident_per_receipt)} | ${pct(a.overall.false_accept_rate)} | ${pct(a.overall.true_accept)} |`;
};
const out = [];
const p = (s = "") => out.push(s);
const BASE = "baseline-phase2-ALL.details.json";
const FIN = "improved-phase2-FINAL4.details.json";
const FIN3 = "improved-phase2-FINAL3.details.json";
const FIN2 = "improved-phase2-FINAL2.details.json";
const H4 = "improved-phase2-HELDOUT4-FIRSTLOOK.details.json";
const H4B = "baseline-phase2-HELDOUT4.details.json";
const has = (f) => fs.existsSync(R(f));

p("# Phase 2 results (generated by scripts/make_report2.mjs; do not edit by hand)\n");
p("Only `pump_name`, `transaction_date`, `total_amount` are scored. **FALSE ACCEPT** = the record would be used without review while a field is wrong (for non-fuel controls: not held for review). **false-confident** = a wrong value on a field not flagged for review.\n");

p("## 1. Label verification status\n");
p(`Label mode in this report: \`${labelSummary.mode}\`. Human-verified labels: **${labelSummary.human_verified}**. Assistant-read PROVISIONAL labels in use: **${labelSummary.assistant_read_provisional_in_use}**. Excluded by policy: ${labelSummary.assistant_read_excluded}. Pending-human-label intake receipts: ${records.filter((r) => r.annotation_status === "pending_human_label").length}.`);
p(`Policy file: ai_review_of_company_receipts_permitted = \`${labelSummary.policy.ai_review_of_company_receipts_permitted}\`; assistant_read_labels = \`${labelSummary.policy.assistant_read_labels}\`.\n`);
p("**No authentic label in this corpus has been verified by a person.** Every authentic figure below depends on labels the assistant read from the page images; they are provisional. Synthetic and control labels are exact by construction and say nothing about real receipts.\n");

p("## 2. Status of every evaluation set\n");
const status = [
  ["authentic dev (12)", "development", "parser and OCR rules were tuned on these"],
  ["authentic 'held-out' (10)", "CONSUMED", "first look was made in phase 1, then fixes followed: development data now; the phase-1 first-look figures are historical"],
  ["synthetic dev (30)", "development", ""],
  ["synthetic held-out (48)", "CONSUMED", "first look in phase 1, fixes followed"],
  ["synthetic held-out2 (48)", "CONSUMED", "first look in phase 1, fixes followed"],
  ["synthetic held-out3 (48)", "CONSUMED (exposed)", "two receipt-level outcomes were printed by the latency investigation and an edge-truncation fix was made after seeing one: development data"],
  ["non-fuel controls (24)", "development", "outcomes were examined while tuning"],
  ["suspected template-generated page (1)", "consumed", "single page"],
  ["synthetic held-out4 (48)", has(H4) ? "CONSUMED after its single first look (below)" : "untouched, not yet run", "generated and hash-frozen BEFORE the code ran on it (reports/FROZEN_BEFORE_HELDOUT4_FIRST_RUN.json); the first look exposed 3 false accepts and a scoring inconsistency, fixes followed: development data now. NO untouched evaluation set remains"],
  ["authentic intake (new Nayara / Jio-bp / Shell / independent receipts)", `${records.filter((r) => String(r.split).startsWith("intake")).length} receipts`, "none could be obtained from an authorized source available to this work; see intake/INTAKE.md"],
];
p("| set | status | note |\n|---|---|---|");
for (const [a, b, c] of status) p(`| ${a} | ${b} | ${c} |`);
const lock = lockStatus(FUEL);
p(`\nHeld-out intake lock: ${lock.locked ? `${lock.receipts} receipts locked ${lock.locked_at}; extractor ${lock.still_untouched ? "unchanged" : "CHANGED: " + lock.changed_files.join(", ")}` : "no lock (no intake receipts exist)"}.\n`);

if (has(FIN) && has(BASE)) {
  p("## 3. AUTHENTIC receipts (provisional labels; all consumed or development; optimistic)\n");
  p(HEAD);
  p(row("existing pipeline (baseline), 22 receipts", load(BASE, ["authentic_dev", "authentic_heldout"])));
  p(row("improved, 22 receipts", load(FIN, ["authentic_dev", "authentic_heldout"])));
  p(row("improved, the 12 development receipts", load(FIN, ["authentic_dev"])));
  p(row("improved, the 10 formerly held-out receipts (now development)", load(FIN, ["authentic_heldout"])));
  p("\nCoverage of authentic receipts by brand: BPCL 12, HP 6, IndianOil 4. **There is no authentic Nayara, Jio-bp, Shell or unfamiliar independent-station receipt**, so the system is untested on them with real data.\n");

  p("## 4. SYNTHETIC receipts (construction labels; robustness only; never evidence of real-world accuracy)\n");
  p(HEAD);
  for (const [name, groups] of [["development (30)", ["synthetic_dev"]], ["held-out (48), consumed", ["synthetic_heldout"]], ["held-out2 (48), consumed", ["synthetic_heldout2"]], ["held-out3 (48), exposed -> development", ["synthetic_heldout3"]]]) {
    p(row(`baseline, ${name}`, load(BASE, groups)));
    p(row(`improved, ${name}`, load(FIN, groups)));
  }
  p(row("baseline, non-fuel controls (24): FALSE ACCEPT = not held for review", load(BASE, ["generic_controls"])));
  p(row("improved, non-fuel controls (24)", load(FIN, ["generic_controls"])));
}
if (has(H4) && has(H4B)) {
  p("\n## 5. UNTOUCHED synthetic held-out4 - the single first look at the final code (fresh layouts for Nayara, Jio-bp, Shell, independent stations)\n");
  p(HEAD);
  p(row("baseline (existing pipeline)", load(H4B, ["synthetic_heldout4"])));
  p(row("improved, FIRST AND ONLY LOOK (code frozen before the run)", load(H4, ["synthetic_heldout4"])));
  p(row("improved, re-run after fix 1 (label phrases, made from DEVELOPMENT data) - a REGRESSION: the regex also stripped real names like 'X STATION - City'", load(FIN2, ["synthetic_heldout4"])));
  p(row("improved, re-run after fix 2 (regression corrected; found by reading the regex and reproduced with a unit test, not from heldout4 failures)", load(FIN3, ["synthetic_heldout4"])));
  p(row("improved, re-run after fix 3 (a brand heading with generic words was taken as the dealer: the 3 false accepts of the first look; DEVELOPMENT-informed from here)", load(FIN, ["synthetic_heldout4"])));
  const rows = load(H4, ["synthetic_heldout4"]);
  p("\n| layout family | n | pump exact | date exact | amount exact | review | false accept |\n|---|---|---|---|---|---|---|");
  const fams = {};
  for (const r of rows) (fams[r.family] ||= []).push(r);
  for (const [k, rs] of Object.entries(fams)) { const a = aggregate(rs); p(`| ${k} | ${rs.length} | ${a.pump_name.exact_rate.n}/${a.pump_name.labelled} | ${a.transaction_date.exact_rate.n}/${a.transaction_date.labelled} | ${a.total_amount.exact_rate.n}/${a.total_amount.labelled} | ${a.overall.review_required_rate.n}/${rs.length} | ${a.overall.false_accept_rate.n}/${rs.length} |`); }
  p("\nheld-out4 is development data after this first look. The FIRST-LOOK row (code frozen before the run) is the unbiased held-out figure for that code; the later rows are not held-out.");
}

p("\n## 6. Every FIRST LOOK, re-scored with the corrected labels (the unbiased held-out figures for the code as it was at each first look)\n");
p("Phase-1 first looks were originally reported with synthetic labels that credited a brand-only pump name as exact; they are re-scored here with the uniform correction. Authentic labels were never affected (still PROVISIONAL, not human-verified). False-accept and false-confident figures were unaffected by that inconsistency except where a brand-only answer had been wrongly counted as correct while usable (none was usable).\n");
p(HEAD);
const firstLooks = [
  ["authentic 'held-out' (10), phase 1 first look [PROVISIONAL labels]", "improved-v5-HELDOUT-FIRSTLOOK.details.json", ["authentic_heldout"]],
  ["synthetic held-out (48), phase 1 first look", "improved-v5-HELDOUT-FIRSTLOOK.details.json", ["synthetic_heldout"]],
  ["synthetic held-out2 (48), phase 1 first look", "improved-v7-HELDOUT2-FIRSTLOOK.details.json", ["synthetic_heldout2"]],
  ["synthetic held-out4 (48), phase 2 first look", H4, ["synthetic_heldout4"]],
];
for (const [name, f, g] of firstLooks) if (has(f)) p(row(name, load(f, g)));
p("\nReading these together: each fresh set of layouts exposed new defects in the extractor as first written (false accepts of roughly 6% to 10% of synthetic records); every defect was a generic one and was fixed, but a fix is only as good as the next unseen layout, and **no untouched evaluation set remains** - any new claim needs new receipts.\n");
for (const f of ["retry-policy-comparison.md"]) if (has(f)) p("\n" + fs.readFileSync(R(f), "utf8"));
if (has("bill_number_month_rule_evidence.md")) p("\n## Bill-number month rule (receipt-family-specific): evidence\n\nSee `reports/bill_number_month_rule_evidence.md` (generated).");
fs.writeFileSync(R("RESULTS_PHASE2.md"), out.join("\n"));
console.log("wrote reports/RESULTS_PHASE2.md");
